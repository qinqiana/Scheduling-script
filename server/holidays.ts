function off(from: string, to: string, name: string): Holiday[] {
  return eachDate(from, to).map((date) =>
    STATUTORY.has(date)
      ? { date, name, kind: "holiday" as const }
      : { date, name: `${name}连休`, kind: "bridge" as const },
  );
}

function work(date: string, name: string): Holiday {
  return { date, name, kind: "workday_makeup" };
}

